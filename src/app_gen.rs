//! The Bevy game around the creator's `index.rs` (decision D01 of gripforgeai/gripforge#420), under `<out>/app/`.
//!
//! The creator writes the rules of the game as one Bevy `Plugin` in `index.rs`, at the root of the project beside
//! `project.gripforge`, and their other modules in `src/` (optional; `src/templates/<id>/` is what `tools/packs copy`
//! writes for the templates of `uses`). The build never copies, writes nor touches them: the generated crate takes them
//! by path (`#[path]`), so the same bytes are compiled and kept.
//!
//!   app/Cargo.toml        its own workspace: bevy, gfkits-bevy-native (the kits in a Bevy game), serde_json
//!   app/src/lib.rs        `index` (the creator's index.rs), the creator's modules of src/ at the root of the crate,
//!                         `game()` (the game.json of the build) and `add_game` (KitsPlugin, then the creator's plugin)
//!   app/src/main.rs       the game in a window: Bevy's default plugins, the mouse of the window and its keys for the kits
//!
//! The plugin is found by convention, with no key in the project: `index.rs` declares one `pub struct X;` with
//! `impl Plugin for X`. Its systems are its own: it orders them (`.after(KitsSet::Step)`), the build adds it after
//! `KitsPlugin` and nothing else. The kits are loaded as by any native gateway (`kitModules` of the game, else
//! `GRIPFORGE_KIT_MODULES`, else `kit-modules-native` beside the program), the game's module `game.main` among them.

use crate::access::relative;
use crate::crate_gen::Sdk;
use serde_json::{json, Value as Json};
use std::path::{Path, PathBuf};

/// The creator's entry, beside the project file.
pub const INDEX: &str = "index.rs";
/// The creator's modules, beside the project file.
pub const SRC: &str = "src";
/// The folder of the Bevy gateway (`gfkits-bevy-native`, Rust name `gfkits_bevy`) in a checkout of the kits repository.
pub const GATEWAY_DIR: &str = "gateways/gfkits-bevy-native/native";
/// Where the gateway is fetched from when the SDK is not a local checkout of the kits repository.
pub const GATEWAY_GIT: &str = "https://github.com/gripforgeai/module-kits";
/// The Bevy the gateway is built on (its workspace pins `=0.20.1`; a compatible requirement unifies with it).
pub const BEVY: &str = "0.20";
/// The inline module that mounts `src/` (its modules re-exported at the root of the crate).
const SRC_MODULE: &str = "game_src";
/// The kits repository revision the public SDK was copied from (`sdk/sdk.json`): the gateway's default revision.
const SDK_JSON: &str = include_str!("../sdk/sdk.json");

const HEADER: &str = "// GENERATED by gripforge-build (gripforge project build) - do not edit: your code is index.rs and src/, beside project.gripforge.";

/// What the creator wrote: their `index.rs`, the plugin it declares, their modules of `src/` (name, file or folder).
#[derive(Debug, Clone, PartialEq)]
pub struct Creator {
    pub index: PathBuf,
    pub plugin: String,
    pub modules: Vec<String>,
    pub src: PathBuf,
}

/// The revision of the kits repository of `sdk/sdk.json`.
pub fn gateway_rev() -> String {
    serde_json::from_str::<Json>(SDK_JSON)
        .ok()
        .and_then(|j| j["rev"].as_str().map(String::from))
        .unwrap_or_default()
}

fn issue(code: &str, file: &Path, message: String, fix: &str) -> Json {
    json!({ "level": "error", "code": code, "file": file.to_string_lossy(), "message": message, "fix": fix })
}

/// Rust source without its comments and the text of its strings: what the plugin is looked for in.
fn code_only(text: &str) -> String {
    let b = text.as_bytes();
    let mut out = String::with_capacity(text.len());
    let mut i = 0;
    while i < b.len() {
        match (b[i], b.get(i + 1)) {
            (b'/', Some(b'/')) => {
                while i < b.len() && b[i] != b'\n' {
                    i += 1;
                }
            }
            (b'/', Some(b'*')) => {
                let mut depth = 0;
                while i < b.len() {
                    if b[i] == b'/' && b.get(i + 1) == Some(&b'*') {
                        depth += 1;
                        i += 2;
                    } else if b[i] == b'*' && b.get(i + 1) == Some(&b'/') {
                        depth -= 1;
                        i += 2;
                        if depth == 0 {
                            break;
                        }
                    } else {
                        i += 1;
                    }
                }
                out.push(' ');
            }
            (b'"', _) => {
                i += 1;
                while i < b.len() && b[i] != b'"' {
                    i += if b[i] == b'\\' { 2 } else { 1 };
                }
                i += 1;
                out.push_str("\"\"");
            }
            _ => {
                out.push(b[i] as char);
                i += 1;
            }
        }
    }
    out
}

/// The tokens of Rust source: identifiers, and every other character but spaces alone.
fn tokens(code: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut word = String::new();
    for c in code.chars() {
        if c.is_alphanumeric() || c == '_' {
            word.push(c);
            continue;
        }
        if !word.is_empty() {
            out.push(std::mem::take(&mut word));
        }
        if !c.is_whitespace() {
            out.push(c.to_string());
        }
    }
    if !word.is_empty() {
        out.push(word);
    }
    out
}

/// The plugin an `index.rs` declares: the one `pub struct X;` with `impl Plugin for X` (`bevy::prelude::Plugin`,
/// `bevy::app::Plugin` too). `Err(candidates)`: none (empty), or several (their names).
pub fn find_plugin(text: &str) -> Result<String, Vec<String>> {
    let t = tokens(&code_only(text));
    let mut impls = Vec::new();
    let mut units = Vec::new();
    for k in 0..t.len() {
        if t[k] == "impl" {
            let end = t[k..]
                .iter()
                .position(|x| x == "for" || x == "{" || x == ";")
                .map(|e| k + e);
            if let Some(e) = end.filter(|e| t[*e] == "for" && *e > k && t[*e - 1] == "Plugin") {
                if let Some(name) = t.get(e + 1) {
                    impls.push(name.clone());
                }
            }
        }
        if t[k] == "pub" && t.get(k + 1).map(String::as_str) == Some("struct") {
            if let (Some(name), Some(";")) = (t.get(k + 2), t.get(k + 3).map(String::as_str)) {
                units.push(name.clone());
            }
        }
    }
    let mut found: Vec<String> = impls.into_iter().filter(|n| units.contains(n)).collect();
    found.dedup();
    match found.len() {
        1 => Ok(found.remove(0)),
        _ => Err(found),
    }
}

fn is_ident(s: &str) -> bool {
    s.chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// The modules of `src/`: each `<m>.rs` and each `<m>/mod.rs`, sorted. A crate root (`lib.rs`, `main.rs`), a module
/// `index` (the creator's index.rs is at the root of the project) or a name that is not a Rust module name is refused.
fn src_modules(src: &Path) -> Result<Vec<String>, Vec<Json>> {
    let Ok(dir) = std::fs::read_dir(src) else {
        return Ok(Vec::new());
    };
    let mut names: Vec<(String, PathBuf)> = Vec::new();
    for e in dir.flatten() {
        let p = e.path();
        let name = e.file_name().to_string_lossy().into_owned();
        if p.is_dir() {
            if p.join("mod.rs").is_file() {
                names.push((name, p));
            }
        } else if let Some(stem) = name.strip_suffix(".rs") {
            names.push((stem.to_string(), p));
        }
    }
    names.sort();
    names.dedup_by(|a, b| a.0 == b.0);
    let mut bad = Vec::new();
    for (name, p) in &names {
        let why = match name.as_str() {
            "lib" | "main" => Some(format!("{} is a crate root: the root of the game's crate is generated (.build/app/src/lib.rs)", p.display())),
            "index" => Some(format!("{} is a module index: index.rs is the creator's plugin, at the root of the project beside project.gripforge", p.display())),
            SRC_MODULE => Some(format!("{} is named like the module that mounts src/ ({SRC_MODULE})", p.display())),
            n if !is_ident(n) => Some(format!("{} is not a Rust module name", p.display())),
            _ => None,
        };
        if let Some(message) = why {
            bad.push(issue("src_module_invalid", p, message, "put the modules of the game in src/<name>.rs or src/<name>/mod.rs, <name> a Rust module name (letters, digits, _), not lib, main nor index; move index.rs beside project.gripforge"));
        }
    }
    if bad.is_empty() {
        Ok(names.into_iter().map(|(n, _)| n).collect())
    } else {
        Err(bad)
    }
}

/// What the creator wrote beside the project (`dir`): `None` without `index.rs` (no Bevy game is written), else their
/// plugin and modules, or the issues that refuse the build.
pub fn creator(dir: &Path) -> Result<Option<Creator>, Vec<Json>> {
    let index = dir.join(INDEX);
    if !index.is_file() {
        return Ok(None);
    }
    let text = std::fs::read_to_string(&index).map_err(|e| {
        vec![issue(
            "index_unreadable",
            &index,
            format!("index.rs cannot be read: {e}"),
            "write index.rs as UTF-8 Rust",
        )]
    })?;
    let mut issues = Vec::new();
    let plugin = match find_plugin(&text) {
        Ok(p) => Some(p),
        Err(found) if found.is_empty() => {
            issues.push(issue("index_plugin_missing", &index,
                "index.rs declares no plugin: no `pub struct X;` with `impl Plugin for X`".into(),
                "write the rules of the game as one Bevy plugin in index.rs: `pub struct MyGame;` and `impl Plugin for MyGame { fn build(&self, app: &mut App) { … } }`, its systems `.after(KitsSet::Step)`"));
            None
        }
        Err(found) => {
            issues.push(issue("index_plugin_ambiguous", &index,
                format!("index.rs declares several plugins ({}): the game is one of them", found.join(", ")),
                "keep one plugin in index.rs, the game's, and let it add the others (`app.add_plugins(…)` in its build)"));
            None
        }
    };
    let src = dir.join(SRC);
    let modules = match src_modules(&src) {
        Ok(m) => m,
        Err(mut i) => {
            issues.append(&mut i);
            Vec::new()
        }
    };
    match plugin {
        Some(plugin) if issues.is_empty() => Ok(Some(Creator {
            index,
            plugin,
            modules,
            src,
        })),
        _ => Err(issues),
    }
}

/// A path for a `#[path]` or a Cargo.toml: relative from `from`, with `/`.
fn rel(from: &Path, to: &Path) -> String {
    relative(from, to).to_string_lossy().replace('\\', "/")
}

/// The `[patch.crates-io]` entries of the kits repository's workspace (`<sdk>/Cargo.toml`), their paths made absolute:
/// the game builds the gateway on the same crates as the kits repository does.
fn patches_of(sdk: &Path) -> String {
    let Ok(text) = std::fs::read_to_string(sdk.join("Cargo.toml")) else {
        return String::new();
    };
    let mut out = String::new();
    let mut inside = false;
    for line in text.lines() {
        let l = line.trim();
        if l.starts_with('[') {
            inside = l == "[patch.crates-io]";
            continue;
        }
        if !inside || l.is_empty() || l.starts_with('#') {
            continue;
        }
        let Some((name, value)) = l.split_once('=') else {
            continue;
        };
        let Some(path) = value
            .split_once("path")
            .and_then(|(_, r)| r.split('"').nth(1))
        else {
            continue;
        };
        out.push_str(&format!(
            "{} = {{ path = {} }}\n",
            name.trim(),
            Json::String(sdk.join(path).to_string_lossy().into_owned())
        ));
    }
    out
}

/// The dependency line of the gateway, and whether it comes by git (the kits repository, private).
fn gateway(sdk: &Sdk) -> (String, Option<String>, bool) {
    let features = ", features = [\"shapes\", \"pointer\"]";
    if let Some(p) = sdk
        .path
        .as_ref()
        .filter(|p| p.join(GATEWAY_DIR).join("Cargo.toml").is_file())
    {
        return (
            format!(
                "gfkits-bevy-native = {{ path = {}{features} }}",
                Json::String(p.join(GATEWAY_DIR).to_string_lossy().into_owned())
            ),
            Some(patches_of(p)),
            false,
        );
    }
    (
        format!(
            "gfkits-bevy-native = {{ git = {}, rev = {}{features} }}",
            Json::String(GATEWAY_GIT.into()),
            Json::String(gateway_rev())
        ),
        None,
        true,
    )
}

/// The Rust name of the game's library (`gripforge_app_<id>`).
pub fn lib_name(project_id: &str) -> String {
    format!("gripforge_app_{}", project_id.replace('-', "_"))
}

/// The Cargo.toml of the app.
pub fn cargo_toml(project_id: &str, version: &str, sdk: &Sdk) -> (String, bool) {
    let (gw, patches, by_git) = gateway(sdk);
    let patch = patches
        .filter(|p| !p.is_empty())
        .map(|p| format!("\n# The crates the kits repository patches, as it builds the gateway.\n[patch.crates-io]\n{p}"))
        .unwrap_or_default();
    let text = format!(
        r#"{header}
# The game {project_id} on Bevy: the kits (gfkits-bevy-native), then the creator's plugin (index.rs).
[package]
name = "gripforge-app-{name}"
version = {version}
edition = "2024"
publish = false

[lib]
name = "{lib}"
path = "src/lib.rs"

[[bin]]
name = "{name}"
path = "src/main.rs"

[dependencies]
# A 3D game with its UI, in a window (no audio: the kits' audio goes through the engine's native player).
bevy = {{ version = "{BEVY}", default-features = false, features = ["3d", "ui"] }}
# The kits in a Bevy game (KitsPlugin, KitsSet, KitsWorldExt), the simple shapes and the mouse of the window.
{gw}
serde_json = "1"
{patch}
# Its own workspace: never a member of the game's folder.
[workspace]

[profile.dev]
opt-level = 1

[profile.release]
opt-level = 3
lto = "thin"
strip = true
"#,
        header = HEADER.replacen("//", "#", 1),
        name = project_id.replace('_', "-"),
        lib = lib_name(project_id),
        version = Json::String(version.into()),
    );
    (text, by_git)
}

/// `lib.rs`: the creator's index.rs and modules by path, the game, the kits then the creator's plugin.
pub fn lib_rs(app_src: &Path, c: &Creator) -> String {
    let src = if c.modules.is_empty() {
        String::new()
    } else {
        format!(
            "\n/// The creator's modules (src/), at the root of the crate: `crate::<module>` (`crate::templates::<template>::index`\n/// for the templates of `uses`).\n#[path = {}]\nmod {SRC_MODULE} {{\n{}}}\npub use {SRC_MODULE}::{{{}}};\n",
            Json::String(rel(app_src, &c.src)),
            c.modules
                .iter()
                .map(|m| format!("    pub mod {m};\n"))
                .collect::<String>(),
            c.modules.join(", ")
        )
    };
    format!(
        r#"{HEADER}
//! The game on Bevy: the kits (gfkits_bevy's `KitsPlugin`), then the creator's plugin (`index::{plugin}`), whose
//! systems run when it says (`.after(KitsSet::Step)`). Nothing of the creator is copied: index.rs and src/ are taken
//! by path.

use bevy::prelude::*;
use serde_json::Value as Json;

/// The engine and the gateway the game is built on, for the game's own tools and tests.
pub use bevy;
pub use gfkits_bevy;

/// The creator's plugin (index.rs, beside project.gripforge: never copied, never written).
#[path = {index}]
pub mod index;
{src}
/// The game the build packed (`.build/game.json`): its kits and their settings, its lock, its scenes for game.engine.
pub const GAME: &str = include_str!("../../game.json");

/// The game as `KitsPlugin` takes it.
pub fn game() -> Json {{
    serde_json::from_str(GAME).expect("game.json, written by gripforge-build")
}}

/// The kits, then the creator's plugin.
pub fn add_game(app: &mut App, game: Json) -> &mut App {{
    app.add_plugins(gfkits_bevy::KitsPlugin::new(game))
        .add_plugins(index::{plugin})
}}
"#,
        plugin = c.plugin,
        index = Json::String(rel(app_src, &c.index)),
    )
}

/// `main.rs`: the game in a window.
pub fn main_rs(project_id: &str) -> String {
    format!(
        r#"{HEADER}
//! The game in a window: Bevy's default plugins, the game (`add_game`), the mouse of the window for the kits
//! (`KitsPointerPlugin`) and its keys handed to the kits' neutral input, as debug.inspector's `forward_keys` does.

use bevy::input::keyboard::KeyboardInput;
use bevy::prelude::*;
use gfkits_bevy::KitGame;

fn main() {{
    let mut app = App::new();
    app.add_plugins(DefaultPlugins);
    {lib}::add_game(&mut app, {lib}::game());
    app.add_plugins(gfkits_bevy::pointer::KitsPointerPlugin)
        .add_systems(PreUpdate, keys)
        .run();
}}

/// The keys of the window to the kits (`KitGame::key`, the code as Bevy names it: `KeyR`, `Space`, `Escape`).
fn keys(mut input: MessageReader<KeyboardInput>, game: Option<NonSendMut<KitGame>>) {{
    let Some(mut game) = game else {{
        input.clear();
        return;
    }};
    for k in input.read().filter(|k| !k.repeat) {{
        game.key(&format!("{{:?}}", k.key_code), k.state.is_pressed());
    }}
}}
"#,
        lib = lib_name(project_id)
    )
}

fn write(file: &Path, text: &str) -> std::io::Result<()> {
    if let Some(d) = file.parent() {
        std::fs::create_dir_all(d)?;
    }
    std::fs::write(file, text)
}

/// Writes the app under `dir`; answers the files written (relative to `dir`) and the warning of a gateway by git.
pub fn write_app(
    dir: &Path,
    project_id: &str,
    version: &str,
    sdk: &Sdk,
    c: &Creator,
) -> std::io::Result<(Vec<String>, Option<Json>)> {
    let src = dir.join("src");
    std::fs::create_dir_all(&src)?;
    let (toml, by_git) = cargo_toml(project_id, version, sdk);
    write(&dir.join("Cargo.toml"), &toml)?;
    if let Some(t) = &sdk.toolchain {
        write(&dir.join("rust-toolchain.toml"), t)?;
    }
    write(&src.join("lib.rs"), &lib_rs(&src, c))?;
    write(&src.join("main.rs"), &main_rs(project_id))?;
    let warning = by_git.then(|| json!({ "level": "warning", "code": "gateway_by_git", "file": dir.join("Cargo.toml").to_string_lossy(),
        "message": format!("the Bevy gateway (gfkits-bevy-native) is taken by git from {GATEWAY_GIT}, a private repository: the app builds only with access to it"),
        "fix": "give a checkout of the kits repository with --sdk <dir> (its gateways/gfkits-bevy-native/native is taken by path)" }));
    Ok((
        ["Cargo.toml", "src/lib.rs", "src/main.rs"]
            .map(String::from)
            .to_vec(),
        warning,
    ))
}
