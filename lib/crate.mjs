/**
 * Writes the Rust crate of a built game under `<out>/game/`: the game's own module (`game.main`), a kit module like
 * any other (core/kit-guest), loaded by the player beside the kits (wasm on the web, a native library elsewhere).
 *
 *   game/Cargo.toml            its own workspace; the SDK crates (core/kit-guest, core/kit-facade) by path or git
 *   game/rust-toolchain.toml   the SDK's toolchain (the same Rust as the kits)
 *   game/kit.api.json          the module's card (id game.main, its version), what the hosts read to load it
 *   game/module.json           its implementations (native library, wasm), like a kit's logic/module.json
 *   game/src/lib.rs            the exports of a kit module (export_kit!, common_memory!)
 *   game/src/index.rs          the module: enters a scene by calling its init_scene, gives it back at the exit
 *   game/src/init_scene/...    written by the generator of core/scene-format (one init_scene.rs per scene), as is
 *
 * The same `index.rs` + `init_scene.rs` as a template's (docs/scene-builder.md, « deux écritures équivalentes »):
 * one generator for the build and the templates. Nothing here knows a kit: the generated code calls the kits'
 * façades (core/kit-facade), which call the host.
 *
 * Used by lib/build.mjs.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { sdkPin } from './compat.mjs';

/** The id of the game's module (the same as the core's GAME_MODULE). */
export const GAME_MODULE = 'game.main';
/** The library name of the module: what the native hosts look for (`gfkit_<kit>`). */
export const LIBRARY = 'gfkit_game_main';
/** Where the SDK is fetched from when no local checkout is given. */
export const SDK_GIT = 'https://github.com/gripforgeai/module-kits';

const HEADER = '// GENERATED by @gripforge/compiler (gripforge project build) - do not edit: change project.gripforge and build again.';

function write(file, text) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
}

/** The dependency line of an SDK crate: by path from a checkout, else by git at the SDK revision. */
function dep(sdk, crate, dir, extra = '') {
  if (sdk.path) return `${crate} = { path = ${JSON.stringify(join(sdk.path, dir))}${extra} }`;
  const pin = /^[0-9a-f]{7,40}$/.test(sdk.rev) ? 'rev' : 'branch';
  return `${crate} = { git = ${JSON.stringify(sdk.git ?? SDK_GIT)}, ${pin} = ${JSON.stringify(sdk.rev)}${extra} }`;
}

/** The Cargo.toml of the game's crate. */
export function cargoToml(projectId, version, sdk) {
  return `${HEADER.replace('//', '#')}
# The game's own module (${GAME_MODULE}) of the project ${projectId}: its scenes posed by compiled code, its kits called
# through their façades (core/kit-facade), never linked.
[package]
name = "gripforge-game-${projectId.replace(/_/g, '-')}"
version = ${JSON.stringify(version)}
edition = "2021"
publish = false

[lib]
name = "${LIBRARY}"
path = "src/lib.rs"
crate-type = ["cdylib", "rlib"]

[features]
default = ["common-memory"]
# The trusted kits' common memory (docs/modules-de-kit.md): the host's allocator on wasm, by pointer.
common-memory = ["gripforge-kit-guest/common-memory"]

[dependencies]
serde_json = "1"
${dep(sdk, 'gripforge-kit-guest', 'core/kit-guest')}
${dep(sdk, 'gripforge-kit-facade', 'core/kit-facade', ', features = ["guest"]')}

# Its own workspace: never a member of the SDK's or of the game's folder.
[workspace]

[profile.dev]
opt-level = 1
debug = 0
panic = "unwind"

[profile.release]
opt-level = "s"
lto = "thin"
strip = true
`;
}

/** `lib.rs`: the exports every kit module has. */
export function libRs() {
  return `${HEADER}
//! The game's own module (${GAME_MODULE}) as a kit module built native and wasm on core/kit-guest.

use gripforge_kit_guest::*;

pub mod index;
pub mod init_scene;

export_kit!(index::module, env!("CARGO_PKG_VERSION"));
common_memory!();
`;
}

/**
 * \`index.rs\`: the module that enters each scene through the generated \`init_scene\` and gives back what it posed at
 * the exit. \`entry\`: the generator's entry (\`init_scene::enter(h, id) -> Option<Posed>\`).
 */
export function indexRs(entry = 'init_scene::enter') {
  return `${HEADER}
//! The game's module: when game.engine enters a scene, its \`init_scene\` poses it (nodes, lights, cameras, the kits'
//! elements) through the kits' façades; when it leaves it, what was posed is given back in the order dev.builder
//! gives it back. The same file over a template's \`init_scene.rs\`.

use crate::host::{KitModule, Kx};
use gripforge_kit_facade::{Json, Posed};
use std::cell::RefCell;
use std::rc::Rc;

thread_local! {
    /// What each entered scene posed, in the order the scenes were entered.
    static POSED: RefCell<Vec<Posed>> = const { RefCell::new(Vec::new()) };
}

/// The module.
pub struct Game;

/// The module as the host takes it.
pub fn module() -> Rc<dyn KitModule> {
    Rc::new(Game)
}

impl KitModule for Game {
    fn id(&self) -> &'static str {
        ${JSON.stringify(GAME_MODULE)}
    }

    fn setup(&self, _kx: &mut Kx) {}

    fn scene_enter(&self, kx: &mut Kx, scene: &Json) {
        let Some(posed) = crate::${entry}(kx, scene["id"].as_str().unwrap_or("")) else {
            return;
        };
        POSED.with(|p| p.borrow_mut().push(posed));
    }

    fn scene_exit(&self, kx: &mut Kx, scene: &Json) {
        let id = scene["id"].as_str().unwrap_or("");
        let posed = POSED.with(|p| {
            let mut p = p.borrow_mut();
            let at = p.iter().rposition(|x| x.scene == id)?;
            Some(p.remove(at))
        });
        if let Some(posed) = posed {
            posed.leave(kx);
        }
    }
}
`;
}

/** The card of the module, what the hosts read to load it beside the kits. */
export function kitApi(version) {
  return {
    schema: 'gripforge.kit-api/1',
    id: GAME_MODULE,
    version,
    requires: [],
    dependencies: {},
    provides: [],
    configSchema: { type: 'object', properties: {} },
    defaults: {},
    events: [],
    services: {},
  };
}

/** Its implementations, as a kit's logic/module.json says them. */
export function moduleJson() {
  const reason = 'the scenes of the project posed by compiled code (gripforge project build): nothing at the tick';
  return {
    implementations: {
      'bevy-player': { form: 'library', library: LIBRARY, mechanism: 'the kits called through their façades', loop: 'tick', thread: 'main', reason },
      'bevy-web': { form: 'wasm', library: GAME_MODULE, mechanism: 'the same module in wasm, in the common memory', loop: 'tick', thread: 'main', reason },
    },
  };
}

/**
 * Writes the crate. `generated`: the generator's files (`[{ path, text }]`, paths under `src/`). The folder `src/init_scene` is emptied first: a scene removed from the project leaves no file.
 */
export function writeCrate(dir, { projectId, version, sdk, generated, entry }) {
  rmSync(join(dir, 'src', 'init_scene'), { recursive: true, force: true });
  rmSync(join(dir, 'src', 'init_scene.rs'), { force: true });
  write(join(dir, 'Cargo.toml'), cargoToml(projectId, version, sdk));
  if (sdk.toolchain) write(join(dir, 'rust-toolchain.toml'), sdk.toolchain);
  write(join(dir, 'kit.api.json'), `${JSON.stringify(kitApi(version), null, 1)}\n`);
  write(join(dir, 'module.json'), `${JSON.stringify(moduleJson(), null, 1)}\n`);
  write(join(dir, 'src', 'lib.rs'), libRs());
  write(join(dir, 'src', 'index.rs'), indexRs(entry));
  for (const f of generated) {
    const to = join(dir, 'src', f.path);
    if (relative(join(dir, 'src'), to).startsWith('..')) throw Error(`the generator wrote outside src/: ${f.path}`);
    write(to, f.text);
  }
  return { dir, files: ['Cargo.toml', 'kit.api.json', 'module.json', 'src/lib.rs', 'src/index.rs', ...generated.map((f) => `src/${f.path}`)] };
}

/** The SDK the crate is built against: a module-kits checkout (`path`), else git at a revision. */
export function sdkOf(path, rev) {
  if (path) {
    const tc = join(path, 'rust-toolchain.toml');
    return { path, toolchain: existsSync(tc) ? readFileSync(tc, 'utf8') : null };
  }
  return { git: process.env.GRIPFORGE_SDK_GIT ?? SDK_GIT, rev: rev ?? process.env.GRIPFORGE_SDK_REV ?? sdkPin().rev, toolchain: null };
}
