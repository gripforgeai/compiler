//! The build into Rust (docs/design/build-gripforge.md): every scene of a `project.gripforge` written as the Rust code
//! that poses it, `init_scene.rs` and one `init_scene/<scene>.rs` per scene. The code does what the dev.builder kit
//! does when the scene is entered (nodes of the engine's tree, light and camera nodes, the kits' sections in their
//! order), decided ahead of time from the same resolution (`build::resolve_scene`) and the same rules
//! ([`crate::place`]); it calls the kits through their Rust accessors (one crate per kit, `gripforge-kit-access-<kit>`,
//! shipped in the kit's folder and generated from its `kit.api.json` by tools/kit-api), never through a line of a kit:
//! the kits stay modules loaded apart.
//!
//! The same writer serves the build of a game (`gfscene code`, `gripforge project build`) and the templates (a
//! template is a `project.gripforge` and this `init_scene.rs`, beside its own `index.rs`).
//!
//! Who uses it: the `gfscene` tool (`code`), the test of kits/dev_builder/tests/build.rs.

use crate::build::resolve_scene;
use crate::issue::{has_errors, Issue};
use crate::math::Transform;
use crate::place::{
    camera_look, camera_params, kits_of, light_params, name_of, ordered, resolve_section, wanted,
    Wanted,
};
use crate::project::validate_project;
use crate::registry::{Element, Field, Registry};
use crate::tree::{Files, Node, Tree};
use serde_json::Value as Json;
use std::collections::HashMap;
use std::fmt::Write as _;

/// The marker of every generated file (its first line).
pub const MARKER: &str = "GENERATED by gfscene code";

/// The issues a build into code refuses although the tolerant reader only warns: a reference that does not hold
/// (a sub-scene file that is not there, a loop of sub-scenes, a reflection that names no node) would be a scene
/// silently different from what the files say.
pub const BROKEN_REFERENCES: &[&str] =
    &["scene_file_missing", "scene_cycle", "reflect_node_unknown"];

/// What dev.builder reads in its own config (`installed[].config` of dev.builder): the same defaults as its
/// kit.api.json (`lights`, `cameras`: true; `lookAhead`: 10).
#[derive(Clone, Debug, PartialEq)]
pub struct Options {
    /// Light nodes are placed through core.light.
    pub lights: bool,
    /// Camera nodes are placed through core.camera.
    pub cameras: bool,
    /// How far ahead of a camera node its point of view is, metres.
    pub look_ahead: f64,
}

impl Options {
    /// The options a project gives dev.builder (its config when installed, else the defaults).
    pub fn of(project: &Json) -> Self {
        let cfg = installed(project)
            .into_iter()
            .find(|(id, _)| id == "dev.builder")
            .map(|(_, c)| c)
            .unwrap_or(Json::Null);
        Options {
            lights: cfg.get("lights") != Some(&Json::Bool(false)),
            cameras: cfg.get("cameras") != Some(&Json::Bool(false)),
            look_ahead: cfg.get("lookAhead").and_then(Json::as_f64).unwrap_or(10.0),
        }
    }
}

/// The kits the project installs, with their config.
fn installed(project: &Json) -> Vec<(String, Json)> {
    project
        .get("installed")
        .and_then(Json::as_array)
        .into_iter()
        .flatten()
        .filter_map(|k| {
            Some((
                k.get("id")?.as_str()?.to_string(),
                k.get("config").cloned().unwrap_or(Json::Null),
            ))
        })
        .collect()
}

/// What `code` produces: the files (relative paths → Rust text) and the warnings.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Generated {
    /// `init_scene.rs`, then `init_scene/<scene>.rs` per scene.
    pub files: Vec<(String, String)>,
    /// What the files say that the code could not honour exactly (warnings; an error refuses the build).
    pub issues: Vec<Issue>,
}

/// Writes the Rust code of every scene of `project`. `reg` holds the kits' declarations (their kit.api.json); only
/// the kits the project installs are taken, as only they are loaded with the game. `Err`: the errors (a required kit
/// missing, a broken reference), nothing written.
pub fn code(
    project: &Json,
    disk: Files,
    reg: &Registry,
    origin: &str,
) -> Result<Generated, Vec<Issue>> {
    // The scene files the project carries (one-file form, `data.scene_files`) first, then the disk's.
    let carried = crate::build::carried(project);
    let read = |p: &str| carried.get(p).cloned().or_else(|| disk(p));
    let files: Files = &read;
    let mut issues = validate_project(project, files, reg);
    for i in issues
        .iter_mut()
        .filter(|i| BROKEN_REFERENCES.contains(&i.code))
    {
        i.level = crate::issue::Level::Error;
    }
    if has_errors(&issues) {
        return Err(issues);
    }
    let kits: Vec<String> = installed(project).into_iter().map(|(id, _)| id).collect();
    let mut reg = reg.clone();
    reg.sections.retain(|k, _| kits.contains(k));
    let opt = Options::of(project);
    let mut out = Generated {
        files: Vec::new(),
        issues,
    };
    let mut scenes: Vec<(String, String)> = Vec::new();
    for scene in project
        .pointer("/data/scenes")
        .and_then(Json::as_array)
        .into_iter()
        .flatten()
    {
        let Some(id) = scene.get("id").and_then(Json::as_str) else {
            continue;
        };
        let Some((file, tree)) = resolve_scene(scene, &reg, files) else {
            continue;
        };
        let module = ident(&snake(id));
        let mut w = Writer {
            reg: &reg,
            kits: &kits,
            opt: &opt,
            issues: Vec::new(),
        };
        let text = w.scene(id, &file, &tree, origin);
        out.issues.extend(w.issues);
        out.files.push((format!("init_scene/{module}.rs"), text));
        scenes.push((id.to_string(), module));
    }
    out.files
        .insert(0, ("init_scene.rs".to_string(), index(&scenes, origin)));
    Ok(out)
}

/// `init_scene.rs`: the scenes, and the call that poses one by its id.
fn index(scenes: &[(String, String)], origin: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "// {MARKER} from {origin} - do not edit; run: gripforge-build <project>");
    s.push_str("//! The scenes of the project posed in code: what dev.builder would do when each one is entered, written\n");
    s.push_str("//! ahead of time. The game calls `enter` from its `scene_enter` and `Posed::leave` from its `scene_exit`.\n\n");
    s.push_str("use gripforge_kit_access::{Host, Posed};\n\n");
    // Generated: never reformatted (a game's `cargo fmt` would make it differ from what `gfscene code` writes).
    for (_, m) in scenes {
        let _ = writeln!(s, "#[rustfmt::skip]\npub mod {m};");
    }
    let _ = writeln!(s, "\n/// The scenes posed here, by id.\n#[allow(dead_code)]\npub const SCENES: &[&str] = &[{}];", scenes.iter().map(|(id, _)| format!("{id:?}")).collect::<Vec<_>>().join(", "));
    s.push_str("\n/// Poses the scene `id` when it is entered; `None` for a scene the project does not pose.\n");
    s.push_str(
        "pub fn enter(h: &mut (impl Host + ?Sized), id: &str) -> Option<Posed> {\n    match id {\n",
    );
    for (id, m) in scenes {
        let _ = writeln!(s, "        {id:?} => Some({m}::enter(h)),");
    }
    s.push_str("        _ => None,\n    }\n}\n");
    s
}

struct Writer<'a> {
    reg: &'a Registry,
    kits: &'a [String],
    opt: &'a Options,
    issues: Vec<Issue>,
}

fn is_visual(ty: &str) -> bool {
    matches!(ty, "group" | "model" | "shape")
}

/// The ten numbers of a transform as the engine's tree takes it, as Rust.
fn trs(t: &Transform) -> String {
    let v: Vec<f64> = t
        .position
        .iter()
        .chain(t.rotation.iter())
        .chain(t.scale.iter())
        .copied()
        .collect();
    format!(
        "[{}]",
        v.iter().map(|x| float(*x)).collect::<Vec<_>>().join(", ")
    )
}

impl Writer<'_> {
    fn installed(&self, kit: &str) -> bool {
        self.kits.iter().any(|k| k == kit)
    }

    fn scene(&mut self, id: &str, file: &str, tree: &Tree, origin: &str) -> String {
        let mut s = String::new();
        let _ = writeln!(s, "// {MARKER} from {origin} ({file}) - do not edit; run: gripforge-build <project>");
        let _ = writeln!(s, "//! The scene `{id}`: its nodes, lights, cameras and kits' elements, posed in the order dev.builder poses them.\n");
        let mut uses: Vec<String> = Vec::new();
        let mut body = String::new();
        let vars = self.nodes(tree, &mut body);
        self.lights_and_cameras(tree, &mut body, &mut uses);
        self.sections(id, file, tree, &vars, &mut body, &mut uses);
        uses.sort();
        uses.dedup();
        s.push_str("#![allow(unused_imports, unused_variables, clippy::all)]\n\n");
        // One crate per kit: the accessor the kit ships in its own folder (`<kit>/access/rust`, gripforge-kit-access-<kit>).
        for u in &uses {
            let _ = writeln!(s, "use gripforge_kit_access_{u} as {u};");
        }
        s.push_str("use gripforge_kit_access::{json, Host, Json, Posed, Spec};\n\n");
        let _ = writeln!(
            s,
            "/// Poses the scene `{id}`; `Posed::leave` gives it back."
        );
        s.push_str("pub fn enter(h: &mut (impl Host + ?Sized)) -> Posed {\n");
        let _ = writeln!(s, "    let mut p = Posed::new({id:?});");
        s.push_str(&body);
        s.push_str("    p\n}\n");
        s
    }

    /// The group, model and shape nodes in the engine's tree: found by path, else made under the parent's node. Gives
    /// the variable of each node's handle, by path.
    fn nodes(&mut self, tree: &Tree, s: &mut String) -> HashMap<String, String> {
        let mut vars = HashMap::new();
        let shown: Vec<&Node> = tree
            .nodes
            .iter()
            .filter(|n| n.visible && is_visual(&n.ty))
            .collect();
        if !shown.is_empty() {
            s.push_str(
                "    // The nodes of the engine's tree (group, model, shape), parents first.\n",
            );
        }
        for (i, n) in shown.iter().enumerate() {
            let var = format!("n{i}_{}", snake(name_of(&n.path)));
            let parent = vars
                .get(&n.parent)
                .cloned()
                .unwrap_or_else(|| "0".to_string());
            let _ = writeln!(
                s,
                "    let {var} = p.node(h, {parent}, {:?}, {:?}, {});",
                n.path,
                name_of(&n.path),
                trs(&n.world)
            );
            vars.insert(n.path.clone(), var);
        }
        vars
    }

    fn lights_and_cameras(&mut self, tree: &Tree, s: &mut String, uses: &mut Vec<String>) {
        for n in tree.nodes.iter().filter(|n| n.visible) {
            match n.ty.as_str() {
                "light" if self.opt.lights && self.installed("core.light") => {
                    uses.push("core_light".into());
                    let (kind, params) = light_params(n);
                    let _ = writeln!(s, "    // {} (light): core.light adopts the game's own node at this path, else makes one.", n.path);
                    let _ = writeln!(s, "    let r = (|| {{\n        let l = core_light::adopt(h, {:?}, \"\", {kind:?}, {:?})?;", n.path, name_of(&n.path));
                    let _ = writeln!(s, "        if let Err(e) = core_light::set(h, l.clone(), json!({}), 0) {{\n            let _ = core_light::remove(h, l);\n            return Err(e);\n        }}\n        Ok(l)\n    }})();", json_lit(&params));
                    let _ = writeln!(
                        s,
                        "    p.place(core_light::REMOVE, {:?}, \"light\", r);",
                        n.path
                    );
                }
                "camera" if self.opt.cameras && self.installed("core.camera") => {
                    uses.push("core_camera".into());
                    let (at, look) = camera_look(n, self.opt.look_ahead);
                    let (fov, current) = camera_params(n);
                    let pos = |v: [f64; 3]| {
                        format!("[{}, {}, {}]", float(v[0]), float(v[1]), float(v[2]))
                    };
                    let _ = writeln!(s, "    // {} (camera): core.camera adopts the game's own camera at this path, else makes one.", n.path);
                    let _ = writeln!(s, "    let r = (|| {{\n        let c = core_camera::adopt(h, {:?}, \"\", {:?})?;", n.path, name_of(&n.path));
                    let _ = writeln!(s, "        core_camera::set_preset(h, c.clone(), \"fixed\", json!({{ \"position\": {}, \"lookAt\": {} }}), 0)?;", pos(at), pos(look));
                    let _ = writeln!(
                        s,
                        "        core_camera::set_fov(h, c.clone(), json!({}))?;",
                        json_lit(&fov)
                    );
                    if current {
                        s.push_str("        core_camera::activate(h, c.clone(), 0)?;\n");
                    }
                    s.push_str("        Ok(c)\n    })();\n");
                    let _ = writeln!(
                        s,
                        "    p.place(core_camera::REMOVE, {:?}, \"camera\", r);",
                        n.path
                    );
                }
                _ => {}
            }
        }
    }

    fn sections(
        &mut self,
        scene: &str,
        file: &str,
        tree: &Tree,
        vars: &HashMap<String, String>,
        s: &mut String,
        uses: &mut Vec<String>,
    ) {
        let all = wanted(tree, file);
        for kit in ordered(self.reg, &kits_of(&all)) {
            for w in all.iter().filter(|w| w.kit == kit) {
                let Some((el, props, issues)) = resolve_section(self.reg, w) else {
                    continue;
                };
                self.issues.extend(issues);
                let node = tree.nodes.iter().find(|n| n.path == w.node);
                let m = ident(&kit_module(&w.kit));
                uses.push(m.clone());
                self.element(scene, w, &el, &props, node, vars.get(&w.node), &m, s);
            }
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn element(
        &mut self,
        scene: &str,
        w: &Wanted,
        el: &Element,
        props: &Json,
        node: Option<&Node>,
        var: Option<&String>,
        m: &str,
        s: &mut String,
    ) {
        let em = ident(&snake(&el.name));
        let place = if w.node.is_empty() {
            "the scene".to_string()
        } else {
            w.node.clone()
        };
        let _ = writeln!(
            s,
            "    // kits.{} on {place}: the element {} of {}.",
            w.kit, el.name, w.kit
        );
        let transform = node.map_or("None".to_string(), |n| {
            let t = &n.world;
            format!(
                "Some(([{}], [{}], [{}]))",
                t.position
                    .iter()
                    .map(|x| float(*x))
                    .collect::<Vec<_>>()
                    .join(", "),
                t.rotation
                    .iter()
                    .map(|x| float(*x))
                    .collect::<Vec<_>>()
                    .join(", "),
                t.scale
                    .iter()
                    .map(|x| float(*x))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        });
        let id = node
            .and_then(|n| n.id.clone())
            .map_or("None".to_string(), |i| format!("Some({i:?})"));
        let parent = var.map_or("None".to_string(), |v| format!("Some({v})"));
        let _ = writeln!(s, "    let spec = Spec {{ scene: {scene:?}, node: {:?}, id: {id}, transform: {transform}, parent: {parent} }};", w.node);
        let mut fields = String::new();
        for (k, f) in &el.props {
            let v = &props[k];
            if v == &f.default {
                continue;
            }
            let _ = write!(fields, "{}: {}, ", ident(&snake(k)), self.value(f, v, k));
        }
        let _ = writeln!(s, "    let r = {m}::{em}::create(h, &spec, &{m}::{em}::Props {{ {fields}..Default::default() }});");
        let _ = writeln!(
            s,
            "    p.make({m}::{em}::REMOVE, {:?}, \"kits.{}\", r);",
            w.node, w.kit
        );
    }

    /// A property's value as Rust, typed as the accessor declares it (tools/kit-api/langs/rust_facade.mjs).
    fn value(&mut self, f: &Field, v: &Json, key: &str) -> String {
        match f.kind.as_str() {
            "string" | "path" => format!("{:?}.into()", v.as_str().unwrap_or("")),
            "f64" | "f32" | "number" => float(v.as_f64().unwrap_or(0.0)),
            "u32" | "u64" | "i32" | "i64" | "u8" | "u16" => v.as_i64().unwrap_or(0).to_string(),
            "bool" => (v == &Json::Bool(true)).to_string(),
            "f64x3" | "vec3" => {
                let a: Vec<String> = (0..3)
                    .map(|i| float(v[i].as_f64().unwrap_or(0.0)))
                    .collect();
                format!("[{}]", a.join(", "))
            }
            "enum" => format!("{}::{}", pascal(key), pascal(v.as_str().unwrap_or(""))),
            _ => format!("json!({})", json_lit(v)),
        }
    }
}

/// A float as a Rust literal that reads back the same number.
fn float(v: f64) -> String {
    format!("{v:?}")
}

/// A JSON value as the text of a `json!` literal (JSON escapes Rust does not know written its way).
fn json_lit(v: &Json) -> String {
    let t = serde_json::to_string(v).unwrap_or_default();
    let mut out = String::with_capacity(t.len());
    let mut it = t.chars().peekable();
    while let Some(c) = it.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match it.next() {
            Some('u') => {
                let hex: String = (0..4).filter_map(|_| it.next()).collect();
                let _ = write!(out, "\\u{{{hex}}}");
            }
            Some('b') => out.push_str("\\u{8}"),
            Some('f') => out.push_str("\\u{c}"),
            Some('/') => out.push('/'),
            Some(x) => {
                out.push('\\');
                out.push(x);
            }
            None => out.push('\\'),
        }
    }
    out
}

/// The module of a kit's accessor: its id with `.` and `-` as `_` (tools/kit-api/langs/common.mjs `dirOfKit`).
pub fn kit_module(id: &str) -> String {
    id.replace(['.', '-'], "_")
}

/// The words of a name, as tools/kit-api/langs/common.mjs splits them (camel humps and every non-alphanumeric).
fn words(s: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let mut cur = String::new();
    let mut prev: Option<char> = None;
    for c in s.chars() {
        if !c.is_ascii_alphanumeric() {
            if !cur.is_empty() {
                out.push(std::mem::take(&mut cur));
            }
            prev = None;
            continue;
        }
        if c.is_ascii_uppercase()
            && prev.is_some_and(|p| p.is_ascii_lowercase() || p.is_ascii_digit())
            && !cur.is_empty()
        {
            out.push(std::mem::take(&mut cur));
        }
        cur.push(c);
        prev = Some(c);
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

/// `snake_case` as the accessors name things.
pub fn snake(s: &str) -> String {
    words(s)
        .iter()
        .map(|w| w.to_lowercase())
        .collect::<Vec<_>>()
        .join("_")
}

/// `PascalCase` as the accessors name types and variants.
pub fn pascal(s: &str) -> String {
    words(s)
        .iter()
        .map(|w| {
            let mut c = w.chars();
            c.next().map_or(String::new(), |f| {
                f.to_ascii_uppercase().to_string() + c.as_str()
            })
        })
        .collect()
}

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
];

/// An identifier, raw when it is a keyword.
pub fn ident(s: &str) -> String {
    if KEYWORDS.contains(&s) {
        format!("r#{s}")
    } else if s.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("_{s}")
    } else {
        s.to_string()
    }
}
