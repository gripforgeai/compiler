//! Writes the Rust crate of a built game under `<out>/game/`: the game's own module (`game.main`), a kit module like
//! any other (the kits SDK's `gripforge-kit-guest`), loaded by the player beside the kits (wasm on the web, a native library
//! elsewhere).
//!
//!   game/Cargo.toml            its own workspace; the SDK crates (kit-guest, kit-access) by git (this repository's
//!                              sdk/ at the compiler's tag) or path (--sdk);
//!                              the accessor of each kit (`<kit>/access/rust`) by path, at the kit's version
//!   game/rust-toolchain.toml   the SDK's toolchain (the same Rust as the kits), with a local SDK
//!   game/kit.api.json          the module's card (id game.main, its version), what the hosts read to load it
//!   game/module.json           its implementations (native library, wasm), like a kit's logic/module.json
//!   game/src/lib.rs            the exports of a kit module (export_kit!, common_memory!)
//!   game/src/index.rs          the module: enters a scene by calling its init_scene, gives it back at the exit
//!   game/src/init_scene/...    written by the generator (one init_scene.rs per scene), as is

use crate::access::{relative, Access};
use crate::json::pretty;
use serde_json::{json, Value as Json};
use std::path::{Path, PathBuf};

/// The id of the game's module (the same as the core's GAME_MODULE).
pub const GAME_MODULE: &str = "game.main";
/// The library name of the module: what the native hosts look for (`gfkit_<kit>`).
pub const LIBRARY: &str = "gfkit_game_main";
/// Where the SDK crates are fetched from when no local folder is given: this repository, whose `sdk/` holds the public
/// part of the kits SDK (gripforge-abi, gripforge-kit-guest, gripforge-kit-access; see sdk/README.md).
pub const SDK_GIT: &str = "https://github.com/gripforgeai/compiler";
/// The revision of [`SDK_GIT`] the game's crate takes by default: the tag of this compiler's version (`--sdk-rev` or
/// GRIPFORGE_SDK_REV change it).
pub const SDK_REV: &str = concat!("v", env!("CARGO_PKG_VERSION"));

const HEADER: &str = "// GENERATED by gripforge-build (gripforge project build) - do not edit: change project.gripforge and build again.";

/// The SDK the crate is built against: a local folder (`path`, with the crates under `dirs`), else git at a revision.
#[derive(Debug, Clone, PartialEq)]
pub struct Sdk {
    pub path: Option<PathBuf>,
    pub git: String,
    pub rev: String,
    pub toolchain: Option<String>,
}

/// The SDK of a local folder, else git at `rev` (else GRIPFORGE_SDK_REV, else [`SDK_REV`]). The folder is this
/// repository's `sdk/` (the crates at its top: `kit-guest/`, `kit-access/`) or a checkout of the kits repository
/// (under `core/`); its `rust-toolchain.toml` is the game's.
pub fn sdk_of(path: Option<&Path>, rev: Option<&str>) -> Sdk {
    match path {
        Some(p) => Sdk {
            path: Some(p.to_path_buf()),
            git: SDK_GIT.into(),
            rev: String::new(),
            toolchain: std::fs::read_to_string(p.join("rust-toolchain.toml")).ok(),
        },
        None => Sdk {
            path: None,
            git: std::env::var("GRIPFORGE_SDK_GIT").unwrap_or_else(|_| SDK_GIT.into()),
            rev: rev
                .map(String::from)
                .or_else(|| std::env::var("GRIPFORGE_SDK_REV").ok())
                .unwrap_or_else(|| SDK_REV.into()),
            toolchain: None,
        },
    }
}

fn is_commit(rev: &str) -> bool {
    (7..=40).contains(&rev.len())
        && rev
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

/// A release tag: `v` and a version (`v0.1.0`).
fn is_tag(rev: &str) -> bool {
    rev.strip_prefix('v')
        .is_some_and(|v| v.starts_with(|c: char| c.is_ascii_digit()))
}

/// The folder of an SDK crate (`kit-guest`) in a local SDK: at its top (this repository's `sdk/`), else under `core/`
/// (a checkout of the kits repository).
fn sdk_dir(root: &Path, krate: &str) -> PathBuf {
    let top = root.join(krate);
    if top.join("Cargo.toml").is_file() {
        top
    } else {
        root.join("core").join(krate)
    }
}

/// The dependency line of an SDK crate: by path from a local SDK, else by git at the SDK revision (a tag, a commit or
/// a branch).
fn dep(sdk: &Sdk, krate: &str, dir: &str, extra: &str) -> String {
    match &sdk.path {
        Some(p) => format!(
            "{krate} = {{ path = {}{extra} }}",
            Json::String(sdk_dir(p, dir).to_string_lossy().into_owned())
        ),
        None => {
            let pin = if is_tag(&sdk.rev) {
                "tag"
            } else if is_commit(&sdk.rev) {
                "rev"
            } else {
                "branch"
            };
            format!(
                "{krate} = {{ git = {}, {pin} = {}{extra} }}",
                Json::String(sdk.git.clone()),
                Json::String(sdk.rev.clone())
            )
        }
    }
}

/// The dependency lines of the kits' accessors: each by its path relative to the game's crate (`crate_dir`), at the
/// exact version of its kit.
pub fn access_deps(crate_dir: &Path, accessors: &[Access]) -> String {
    accessors
        .iter()
        .map(|f| {
            let path = relative(crate_dir, &f.dir)
                .to_string_lossy()
                .replace('\\', "/");
            format!(
                "{} = {{ path = {}, version = {} }}\n",
                f.krate,
                Json::String(path),
                Json::String(format!("={}", f.version))
            )
        })
        .collect()
}

/// The Cargo.toml of the game's crate. `accessors`: the lines of [`access_deps`].
pub fn cargo_toml(project_id: &str, version: &str, sdk: &Sdk, accessors: &str) -> String {
    format!(
        r#"{header}
# The game's own module ({GAME_MODULE}) of the project {project_id}: its scenes posed by compiled code, its kits called
# through their accessors (one crate per kit, in the kit's folder), never linked.
[package]
name = "gripforge-game-{name}"
version = {version}
edition = "2021"
publish = false

[lib]
name = "{LIBRARY}"
path = "src/lib.rs"
crate-type = ["cdylib", "rlib"]

[features]
default = ["common-memory"]
# The trusted kits' common memory (docs/modules-de-kit.md): the host's allocator on wasm, by pointer.
common-memory = ["gripforge-kit-guest/common-memory"]

[dependencies]
serde_json = "1"
{guest}
{accessor}
# The accessor of each kit, shipped in the kit's folder at the kit's version (gripforge-build never writes one).
{accessors}
# The accessors ask for gripforge-kit-access by version: it is the SDK's, the same crate as above.
[patch.crates-io]
{patched}

# Its own workspace: never a member of the SDK's or of the game's folder.
[workspace]

[profile.dev]
opt-level = 1
debug = 0
panic = "unwind"

[profile.release]
opt-level = "s"
lto = "thin"
strip = true
"#,
        header = HEADER.replacen("//", "#", 1),
        name = project_id.replace('_', "-"),
        version = Json::String(version.into()),
        guest = dep(sdk, "gripforge-kit-guest", "kit-guest", ""),
        accessor = dep(
            sdk,
            "gripforge-kit-access",
            "kit-access",
            ", features = [\"guest\"]"
        ),
        patched = dep(sdk, "gripforge-kit-access", "kit-access", ""),
    )
}

/// `lib.rs`: the exports every kit module has.
pub fn lib_rs() -> String {
    format!(
        r#"{HEADER}
//! The game's own module ({GAME_MODULE}) as a kit module built native and wasm on core/kit-guest.

use gripforge_kit_guest::*;

pub mod index;
pub mod init_scene;

export_kit!(index::module, env!("CARGO_PKG_VERSION"));
common_memory!();
"#
    )
}

/// `index.rs`: enters each scene through the generated `init_scene` and gives back what it posed at the exit.
pub fn index_rs(entry: &str) -> String {
    format!(
        r#"{HEADER}
//! The game's module: when game.engine enters a scene, its `init_scene` poses it (nodes, lights, cameras, the kits'
//! elements) through the kits' accessors; when it leaves it, what was posed is given back in the order dev.builder
//! gives it back. The same file over a template's `init_scene.rs`.

use crate::host::{{KitModule, Kx}};
use gripforge_kit_access::{{Json, Posed}};
use std::cell::RefCell;
use std::rc::Rc;

thread_local! {{
    /// What each entered scene posed, in the order the scenes were entered.
    static POSED: RefCell<Vec<Posed>> = const {{ RefCell::new(Vec::new()) }};
}}

/// The module.
pub struct Game;

/// The module as the host takes it.
pub fn module() -> Rc<dyn KitModule> {{
    Rc::new(Game)
}}

impl KitModule for Game {{
    fn id(&self) -> &'static str {{
        {id}
    }}

    fn setup(&self, _kx: &mut Kx) {{}}

    fn scene_enter(&self, kx: &mut Kx, scene: &Json) {{
        let Some(posed) = crate::{entry}(kx, scene["id"].as_str().unwrap_or("")) else {{
            return;
        }};
        POSED.with(|p| p.borrow_mut().push(posed));
    }}

    fn scene_exit(&self, kx: &mut Kx, scene: &Json) {{
        let id = scene["id"].as_str().unwrap_or("");
        let posed = POSED.with(|p| {{
            let mut p = p.borrow_mut();
            let at = p.iter().rposition(|x| x.scene == id)?;
            Some(p.remove(at))
        }});
        if let Some(posed) = posed {{
            posed.leave(kx);
        }}
    }}
}}
"#,
        id = Json::String(GAME_MODULE.into())
    )
}

/// The card of the module, what the hosts read to load it beside the kits.
pub fn kit_api(version: &str) -> Json {
    json!({
        "schema": "gripforge.kit-api/1", "id": GAME_MODULE, "version": version, "requires": [], "dependencies": {},
        "provides": [], "configSchema": { "type": "object", "properties": {} }, "defaults": {}, "events": [], "services": {}
    })
}

/// Its implementations, as a kit's logic/module.json says them.
pub fn module_json() -> Json {
    let reason = "the scenes of the project posed by compiled code (gripforge project build): nothing at the tick";
    json!({ "implementations": {
        "bevy-player": { "form": "library", "library": LIBRARY, "mechanism": "the kits called through their accessors", "loop": "tick", "thread": "main", "reason": reason },
        "bevy-web": { "form": "wasm", "library": GAME_MODULE, "mechanism": "the same module in wasm, in the common memory", "loop": "tick", "thread": "main", "reason": reason }
    } })
}

fn write(file: &Path, text: &str) -> std::io::Result<()> {
    if let Some(d) = file.parent() {
        std::fs::create_dir_all(d)?;
    }
    std::fs::write(file, text)
}

/// Writes the crate. `generated`: the generator's files (`(path under src/, text)`). The folder `src/init_scene` is
/// emptied first: a scene removed from the project leaves no file. Answers the files written.
pub fn write_crate(
    dir: &Path,
    project_id: &str,
    version: &str,
    sdk: &Sdk,
    accessors: &[Access],
    generated: &[(String, String)],
    entry: &str,
) -> std::io::Result<Vec<String>> {
    std::fs::create_dir_all(dir)?;
    let _ = std::fs::remove_dir_all(dir.join("src/init_scene"));
    let _ = std::fs::remove_file(dir.join("src/init_scene.rs"));
    write(
        &dir.join("Cargo.toml"),
        &cargo_toml(project_id, version, sdk, &access_deps(dir, accessors)),
    )?;
    if let Some(t) = &sdk.toolchain {
        write(&dir.join("rust-toolchain.toml"), t)?;
    }
    write(
        &dir.join("kit.api.json"),
        &format!("{}\n", pretty(&kit_api(version))),
    )?;
    write(
        &dir.join("module.json"),
        &format!("{}\n", pretty(&module_json())),
    )?;
    write(&dir.join("src/lib.rs"), &lib_rs())?;
    write(&dir.join("src/index.rs"), &index_rs(entry))?;
    let mut files: Vec<String> = [
        "Cargo.toml",
        "kit.api.json",
        "module.json",
        "src/lib.rs",
        "src/index.rs",
    ]
    .map(String::from)
    .to_vec();
    for (path, text) in generated {
        if path.split(['/', '\\']).any(|p| p == "..") || Path::new(path).is_absolute() {
            return Err(std::io::Error::other(format!(
                "the generator wrote outside src/: {path}"
            )));
        }
        write(&dir.join("src").join(path), text)?;
        files.push(format!("src/{path}"));
    }
    Ok(files)
}
